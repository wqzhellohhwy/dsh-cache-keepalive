/**
 * 会话 surface 折叠 —— **纯 Node，零依赖**（脱离 DSH 运行时的核心一步）。
 *
 * ## 为什么需要它
 * 保温要发的请求体 = 「这条会话下一次真实请求的前缀」。日志里存的是**事件流**，
 * 得先折成「模型可见的消息序列」才能发请求。这一步 DSH 用 `@deepseek-ai/dsh-session`
 * 的 `foldSurface` / `foldRequestHeader` / `deriveEventMessage` 做。
 * 插件半边能直接拿活的 agent（`requestHeader()` + `deriveMessages()`），
 * 独立 CLI 没有活对象，只能从日志重建 —— 于是必须复刻这三个函数。
 *
 * ## 为什么复刻是安全的
 * 三个函数真正承载语义的部分很短：
 *  - `foldRequestHeader`：取**最后一个** `request/header`，做一次规范化
 *  - `deriveEventMessage`：按事件类型取 `data.message`
 *  - `foldSurface`：`append` 推入节点、`replace` 用 splice 换掉一段
 * 官方实现其余约 180 行全是**防御性断言**（seq 连续、范围存在、tool_use 只能改 content、
 * system 头受保护…）。那些断言保护的是「往日志里写」；离线只读已经落盘、已经过校验的日志，
 * 保留其中会影响**结果正确性**的几条即可，其余省略。
 *
 * 实测（2026-10-17，本机全部 319 个会话）：本模块与官方实现对 `nodes`、`request/header`、
 * 消息推导**逐项完全一致，0 差异、0 抛错**。
 *
 * ## 硬边界
 * `image/offload` 事件需要**外部消息投影器**（DSH 的压缩插件注册的），算法不在本仓库，
 * 所以遇到它一律明确抛错，不猜。本机 319 个会话该事件出现 **0 次**，暂不影响使用。
 * 压缩 / 剪枝不需要投影器 —— 它们的结果已经以 `surfaceOp: {op:'replace'}` 落进日志。
 */
import type { ToolDecl } from './toolhistory.ts'

/** 会进入「模型可见 surface」的事件类型。 */
export const SURFACE_EVENT_TYPES: ReadonlySet<string> = new Set([
  'system/message',
  'developer/message',
  'user/message',
  'assistant/message',
  'tool/result',
  /**
   * ⚠️ **`compaction/summary` 不在这里，别加**。
   *
   * 它是**纯元数据**（记录压缩用了哪个模型、多少 token、遮蔽了哪些 seq），
   * **真正的 replace 是它后面紧跟的那条 `user/message`** —— 实测 40b9：
   * 14/14 条 `compaction/summary` 都配对一条 `source.kind === 'compact-checkpoint'`
   * 且 `surfaceOp: {op:'replace', …}` 的 user 消息（例如
   * `summary#43532` ↔ `user#43533`，后者 `replace{37503→43523}`）。
   *
   * 把 summary 也当 surface 事件加进来，会让同一条摘要**投影两次**
   * （实测 40b9 装配出 2 条内容相同的 checkpoint，真实只有 1 条）。
   */
])

/** 必须靠外部投影器才能折叠的事件类型（算法不在本仓库）。 */

export const PROJECTION_REQUIRED_TYPES: ReadonlySet<string> = new Set(['image/offload'])

/**
 * **压缩摘要渲染成模型可见消息时的三段包装**（`dsh-compaction-basic/lib/index.js:234-235,280,344-356`）：
 * ```js
 * const CHECKPOINT_PREAMBLE = "This is an automatically generated checkpoint condensing …"
 * const SUMMARY_OPEN_TAG  = "<compacted-summary>"
 * const SUMMARY_CLOSE_TAG = "</compacted-summary>"
 * function frameSummary(summary) {
 *   return [
 *     { type: 'text', text: `${CHECKPOINT_PREAMBLE}\n\n${SUMMARY_OPEN_TAG}` },
 *     ...summary,
 *     { type: 'text', text: SUMMARY_CLOSE_TAG },
 *   ]
 * }
 * ```
 * ⚠️ **不能直接把 `data.summary` 当消息内容** —— 真实请求里那是一条 11862 字符的
 * user 消息，**开头是 preamble**，而 `data.summary` 开头是 `## Primary Request and Intent`。
 * 少了这层包装，第一条就与真实请求不同。
 */
export const CHECKPOINT_PREAMBLE = 'This is an automatically generated checkpoint condensing an earlier span'
  + ' of the conversation to free up context. Treat the captured context as established background'
  + ' and build on it without restating it. Continue the task directly from the messages that follow,'
  + ' without acknowledging this checkpoint.'
export const SUMMARY_OPEN_TAG = '<compacted-summary>'
export const SUMMARY_CLOSE_TAG = '</compacted-summary>'

/**
 * 换模型提示的前缀（DSH `dsh-agent/lib/types/model-selection.js:18` 生成的 user 消息）。
 *
 * 完整格式：
 * `[model changed: assistant turns above this point were generated by <from>; the session continues with <to>]`
 */
export const MODEL_CHANGED_PREFIX = '[model changed: '

/**
 * 一条 `model/selection` 事件是否会产生「换模型提示」。
 *
 * ## 规则（`model-selection.js:76-88`，逐条对应）
 * 在 `agent/pre-step` 里，把**已装配的选择**与**上一次请求头的 config** 比：
 * ```js
 * const selected = selection.assembled;
 * const previous = agent.session.requestHeader()?.config;
 * if (selected === undefined || previous === undefined || sameRoute(selected, previous)) return decision;
 * return { ...decision, messages: [...decision.messages, modelSwitchNotice(previous, selected)] };
 * // sameRoute: provider 相同 && model 相同
 * ```
 * **只看 provider/model，不看 reasoningEffort**（`:38` 「effort-only changes … add no notice」），
 * 所以实测 5 条 `model/selection` 只产生了 **2 条**提示（两次 effort 变化不产生）。
 *
 * @param previous 上一次请求头的 config（`{provider, model}`）
 * @param selected 本次 `model/selection` 的 `{provider, model}`
 * @returns 需要提示时返回 `{from, to}` 标签；否则 undefined
 */
export function modelSwitchOf(
  previous: { provider?: unknown; model?: unknown } | undefined,
  selected: { provider?: unknown; model?: unknown } | undefined,
): { from: string; to: string } | undefined {
  if (previous === undefined || selected === undefined) return undefined
  const p = previous
  const s = selected
  if (p.provider === s.provider && p.model === s.model) return undefined
  const label = (route: { provider?: unknown; model?: unknown }, other: { provider?: unknown; model?: unknown }): string =>
    route.provider === other.provider ? String(route.model) : `${String(route.provider)}/${String(route.model)}`
  return { from: label(p, s), to: label(s, p) }
}

/** 生成一条换模型提示消息（与 `modelSelectionNotice` 同形）。 */
export function modelSwitchNoticeMessage(from: string, to: string): DerivedMessage {
  return {
    role: 'user',
    content: [{
      type: 'text',
      text: `${MODEL_CHANGED_PREFIX}assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
    }],
    source: { kind: 'model-selection', form: 'notice' },
  }
}

/** 位置替换操作。 */
export interface ReplaceOp {
  op: 'replace'
  /** 被替换区间的起始事件 seq（必须是更早的、当前在 surface 里的节点）。 */
  startSeq: number
  /** 被替换区间的结束 seq（含）。 */
  endSeq: number
}

/** 一次折叠里能决定消息序列的全部字段。 */
export interface SurfaceEvent {
  type?: string
  seq?: number
  /** `'append'` = 追加到尾部；replace 对象 = 用本事件替换掉那段区间。 */
  surfaceOp?: 'append' | ReplaceOp
  data?: Record<string, unknown>
  [key: string]: unknown
}

/** 折叠结果。 */
export interface SurfaceFold {
  /** 模型可见的事件 seq，**顺序即模型看到的顺序**。 */
  nodes: number[]
  /**
   * 被投影器改写过的消息（seq → message）。
   * 本项目不实现任何投影器，所以恒为空；留着是为了让消费方与官方 API 形状一致。
   */
  projectedMessages: Map<number, unknown>
  /** 发生过多少次位置替换（诊断用：非 0 说明这条会话被压缩或剪枝过）。 */
  replacements: number
}

/** 折叠选项。 */
export interface FoldOptions {
  /** 首个事件的绝对 seq（全量读日志时为 0；读日志窗口时传窗口起点）。 */
  baseSeq?: number
  /**
   * 严格模式（默认 true）：seq 不连续、replace 范围找不到、surface 事件缺 `surfaceOp`
   * 一律抛错。关掉后跳过异常事件继续折 —— 只在排查坏日志时用，正常路径别关。
   */
  strict?: boolean
}

/** 是否为合法的非负安全整数。 */
function isSeq(value: unknown): value is number {
  return typeof value === 'number' && Number.isSafeInteger(value) && value >= 0
}

/** 是否为合法的 replace 操作。 */
export function isReplaceOp(value: unknown): value is ReplaceOp {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) return false
  const op = value as Record<string, unknown>
  return op['op'] === 'replace' && isSeq(op['startSeq']) && isSeq(op['endSeq'])
}

/**
 * 取一个事件的 surface 操作。
 *
 * ⚠️ `compaction/summary` **不进 surface**（见 `SURFACE_EVENT_TYPES` 的注释）：
 * 真正的 replace 是它后面那条 `compact-checkpoint` 的 `user/message`。
 *
 * @returns `'append'`、replace 对象，或 `undefined`（该事件不进 surface）
 */
function surfaceOpOf(event: SurfaceEvent, index: number, strict: boolean): 'append' | ReplaceOp | undefined {
  if (event.type === 'compaction/summary') return undefined
  const isSurfaceType = SURFACE_EVENT_TYPES.has(String(event.type))
  const raw = event.surfaceOp
  if (!isSurfaceType) {
    /**
     * 非 surface 类型（`tool/call`、`step/start`、`request/header` …）**不能**带 surfaceOp。
     * 带了说明日志有结构问题；严格模式下报出来，免得后面的命中率异常被误判成装配 bug。
     */
    if (raw !== undefined && strict) {
      throw new Error(`事件 #${index}（${String(event.type)}）不是 surface 类型，却带着 surfaceOp`)
    }
    return undefined
  }
  if (raw === undefined) {
    // 官方在这里也抛错：surface 类型事件必须显式声明自己是 append 还是 replace
    if (strict) throw new Error(`事件 #${index}（${String(event.type)}）是 surface 类型，但缺 surfaceOp`)
    return undefined
  }
  if (raw === 'append') return raw
  if (!isReplaceOp(raw)) {
    if (strict) throw new Error(`事件 #${index}（${String(event.type)}）的 surfaceOp 形状非法`)
    return undefined
  }
  return raw
}

/**
 * 折叠出「模型可见的节点顺序」。
 *
 * 语义与官方 `foldSurface` 一致：
 *  - `append` → 追加到尾部
 *  - `replace` → 在 nodes 里定位 startSeq 与 endSeq，用本事件的 seq 替换整段
 *    （压缩、剪枝、工具结果改写都走这一条）
 *
 * @param events 会话事件（**按 seq 升序**，全量读时 seq 应为 0,1,2…）
 * @param options 折叠选项
 */
export function foldSurface(events: readonly SurfaceEvent[], options: FoldOptions = {}): SurfaceFold {
  const baseSeq = options.baseSeq ?? 0
  const strict = options.strict !== false
  const nodes: number[] = []
  const projectedMessages = new Map<number, unknown>()
  let replacements = 0

  for (let index = 0; index < events.length; index += 1) {
    const event = events[index]
    const expected = baseSeq + index
    if (event.seq !== expected) {
      if (strict) {
        throw new Error(
          `事件 seq 不连续：第 ${index} 个事件的 seq 是 ${String(event.seq)}，应为 ${expected}。`
          + '（读全量日志时若混入了不带 seq 的会话头，会触发这一条 —— 先过滤掉无 seq 的事件。）',
        )
      }
      continue
    }
    if (PROJECTION_REQUIRED_TYPES.has(String(event.type))) {
      throw new Error(
        `事件 ${String(event.type)}（seq ${event.seq}）需要外部消息投影器才能折叠，本仓库没有实现它。`
        + '本机全部会话里该事件出现 0 次；若真遇到，说明这条会话用了图片卸载功能，需要补一个投影器。',
      )
    }
    const op = surfaceOpOf(event, index, strict)
    if (op === undefined) continue
    if (op === 'append') {
      nodes.push(event.seq)
      continue
    }
    const startIdx = nodes.indexOf(op.startSeq)
    const endIdx = nodes.indexOf(op.endSeq)
    if (startIdx < 0 || endIdx < 0 || startIdx > endIdx) {
      if (strict) {
        throw new Error(
          `事件 seq ${event.seq} 的 replace 范围 ${op.startSeq}→${op.endSeq} 不在当前 surface 里`
          + `（startIdx=${startIdx} endIdx=${endIdx}）。`,
        )
      }
      continue
    }
    nodes.splice(startIdx, endIdx - startIdx + 1, event.seq)
    replacements += 1
  }

  return { nodes, projectedMessages, replacements }
}

/** 请求头里的采样参数（字段原样透传，不解释）。 */
export interface RequestConfig {
  provider?: string
  model?: string
  reasoningEffort?: unknown
  temperature?: number
  maxTokens?: number
  stop?: readonly string[]
  [key: string]: unknown
}

/** 规范化后的请求头。 */
export interface RequestHeader {
  config?: RequestConfig
  adapterDefaults?: { reasoningEffort?: boolean; maxTokens?: boolean }
  tools?: ToolDecl[]
}

/**
 * 取**最后一次** `request/header` 并规范化。
 *
 * 规范化规则与官方 `canonicalHeader` 一致：
 *  - `tools` 为空数组时**视为没有这个字段**（真实请求就是这样发的）
 *  - `adapterDefaults` 只在它真的声明了 reasoningEffort / maxTokens 时保留
 *  - `system` 不在 header 里（走 `system/message`）
 *
 * @param events 会话事件
 * @returns 最后一次请求头；从未请求过时返回 `undefined`
 */
export function foldRequestHeader(events: readonly SurfaceEvent[]): RequestHeader | undefined {
  let state: RequestHeader | undefined
  for (const event of events) {
    if (event.type !== 'request/header') continue
    const data = event.data as { header?: Record<string, unknown> } | undefined
    const header = (data?.header ?? {}) as RequestHeader & { adapterDefaults?: Record<string, unknown> }
    const defaults = header.adapterDefaults
    const keepDefaults = defaults?.reasoningEffort === true || defaults?.maxTokens === true
    state = {
      ...(header.config !== undefined ? { config: header.config } : {}),
      ...(keepDefaults ? { adapterDefaults: defaults as RequestHeader['adapterDefaults'] } : {}),
      ...(Array.isArray(header.tools) && header.tools.length > 0 ? { tools: header.tools } : {}),
    }
  }
  return state
}

/** 模型消息的最小形态（字段原样透传）。 */
export interface DerivedMessage {
  role?: string
  content?: { type?: string; text?: string; [key: string]: unknown }[]
  id?: string
  [key: string]: unknown
}

/**
 * 把一条事件投影成模型消息。
 *
 * 与官方 `deriveEventMessage` 一致：
 *  - `user/message` → `event.data` 本身就是消息
 *  - `system` / `developer` / `assistant` → `event.data.message`，**内容为空串时丢弃**
 *  - `tool/result` → `event.data.message`
 *  - 其余事件（日志记录、边界事件）→ `null`
 *
 * @param event 事件
 * @param projectedMessages 折叠时产生的投影消息表（本项目恒空，留参数为了形状一致）
 */
export function deriveEventMessage(
  event: SurfaceEvent,
  projectedMessages?: ReadonlyMap<number, unknown>,
): DerivedMessage | null {
  if (projectedMessages !== undefined && typeof event.seq === 'number') {
    const projected = projectedMessages.get(event.seq)
    if (projected !== undefined) return projected as DerivedMessage
  }
  switch (event.type) {
    case 'user/message':
      return (event.data ?? null) as DerivedMessage | null
    case 'system/message':
    case 'developer/message':
    case 'assistant/message': {
      const message = (event.data as { message?: DerivedMessage } | undefined)?.message
      if (message === undefined) return null
      if (!Array.isArray(message.content) || message.content.length === 0) return null
      return message
    }
    case 'tool/result':
      return ((event.data as { message?: DerivedMessage } | undefined)?.message) ?? null
    /**
     * **压缩摘要**：投影成一条 `user` 消息，内容 = `frameSummary(data.summary)`
     * （`dsh-compaction-basic/lib/index.js:344-356`）。
     *
     * 真实请求里看到的就是这个 —— 实测 `.tmp/spy-exp` 索引 1 是 11862 字符，
     * 开头 `This is an automatically generated checkpoint condensing …`。
     */
    case 'compaction/summary': {
      const raw = (event.data as { summary?: unknown } | undefined)?.summary
      const summary = Array.isArray(raw)
        ? (raw as { type?: string; text?: string }[])
        : typeof raw === 'string' && raw !== '' ? [{ type: 'text', text: raw }] : []
      if (summary.length === 0) return null
      return {
        role: 'user',
        content: [
          { type: 'text', text: `${CHECKPOINT_PREAMBLE}\n\n${SUMMARY_OPEN_TAG}` },
          ...summary,
          { type: 'text', text: SUMMARY_CLOSE_TAG },
        ],
        source: { kind: 'compaction', form: 'summary' },
      }
    }
    default:
      return null
  }
}

/**
 * 一步到位：事件流 → 模型消息序列。
 *
 * 这是 CLI 真正要的东西 —— 省掉「先折 nodes、再按 seq 反查事件」的两段式。
 *
 * @param events 会话事件（按 seq 升序、seq 从 `options.baseSeq` 起连续）
 * @param options 折叠选项
 */
export function messagesOf(
  events: readonly SurfaceEvent[],
  options: FoldOptions = {},
): { messages: DerivedMessage[]; surface: SurfaceFold } {
  const surface = foldSurface(events, options)
  const bySeq = new Map<number, SurfaceEvent>()
  for (const event of events) if (typeof event.seq === 'number') bySeq.set(event.seq, event)
  const messages: DerivedMessage[] = []
  for (const seq of surface.nodes) {
    const event = bySeq.get(seq)
    if (event === undefined) continue
    const message = deriveEventMessage(event, surface.projectedMessages)
    if (message !== null) messages.push(message)
  }
  return { messages, surface }
}

